import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import initSqlJs from 'sql.js';
import { build } from 'vite';
import { nativeAliases } from '../../mobile/vite-aliases.ts';

test('mobile document drafts durably recover, protect attachments and publish atomically across restarts', async t => {
  const folder = resolve('test-results/native-document-drafts'); await mkdir(folder, { recursive: true });
  await build({ configFile: false, logLevel: 'error', define: { 'process.env': '{}' }, resolve: { alias: nativeAliases }, build: { outDir: folder, emptyOutDir: false, minify: false, lib: { entry: resolve('mobile/runtime.ts'), formats: ['es'], fileName: () => 'runtime.mjs' } } });
  const { createLocalRuntime } = await import(pathToFileURL(resolve(folder, 'runtime.mjs')).href);
  const sql = await initSqlJs({ locateFile: () => resolve('node_modules/sql.js/dist/sql-wasm.wasm') });
  const seed = { schemaVersion: 1, domains: [], categories: [], tags: [], questions: [], documents: [], papers: [] };
  let durable: Uint8Array | undefined, failSave = false, saves = 0;
  const storage = { async load() { return durable?.slice(); }, async save(bytes: Uint8Array) { if (failSave) throw new Error('test disk full'); durable = bytes.slice(); saves++; } };
  let runtime = await createLocalRuntime(sql, seed, storage, { dailyPushScheduler: false }); t.after(() => runtime.close());
  const api = async (url: string, method = 'GET', data?: unknown, expected = 200): Promise<any> => {
    const response = await runtime.fetch(url, { method, headers: { 'Content-Type': 'application/json' }, ...(data === undefined ? {} : { body: JSON.stringify(data) }) });
    const value = await response.json(); assert.equal(response.status, expected, JSON.stringify(value)); return value;
  };
  const state = { title: '', kind: '', bodyMarkdown: '未命名的草稿正文', collection: 'general', categoryIds: [], tagIds: [], domainIds: [], author: '', publisher: '', publishedYear: '', description: '', sourcePath: null, format: 'markdown', assetId: null, fileName: null };
  let draft = await api('/api/document-drafts', 'POST', { documentId: null, baseDocumentUpdatedAt: null, state }, 201);
  assert.equal((await api('/api/documents')).length, 0);
  await runtime.close(); runtime = await createLocalRuntime(sql, seed, storage, { dailyPushScheduler: false });
  assert.equal((await api('/api/document-drafts'))[0].state.bodyMarkdown, state.bodyMarkdown);
  const before = durable!.slice(), beforeReads = saves; failSave = true;
  await api('/api/document-drafts'); assert.equal(saves, beforeReads); assert.deepEqual(durable, before);
  await api(`/api/document-drafts/${draft.id}`, 'PUT', { expectedUpdatedAt: draft.updatedAt, state: { ...state, bodyMarkdown: '失败写入不能被确认' } }, 507);
  assert.deepEqual(durable, before); failSave = false;
  const old = draft; draft = await api(`/api/document-drafts/${draft.id}`, 'PUT', { expectedUpdatedAt: draft.updatedAt, state: { ...state, bodyMarkdown: '继续编辑同一份草稿' } });
  assert.equal(draft.id, old.id); assert.equal((await api('/api/document-drafts')).length, 1);
  await api(`/api/document-drafts/${draft.id}`, 'PUT', { expectedUpdatedAt: old.updatedAt, state }, 409);
  await api(`/api/document-drafts/${draft.id}/publish`, 'POST', { expectedUpdatedAt: draft.updatedAt }, 400);
  assert.equal((await api('/api/document-drafts')).length, 1);
  const asset = await api('/api/assets', 'POST', { filename: 'draft.png', mimeType: 'image/png', dataBase64: 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=' }, 201);
  const complete = { ...draft.state, title: '保存为正式资料', kind: '学习笔记', bodyMarkdown: `图片引用\n\n![草稿图片](/api/assets/${asset.id}/content)` };
  draft = await api(`/api/document-drafts/${draft.id}`, 'PUT', { expectedUpdatedAt: draft.updatedAt, state: complete });
  await api(`/api/assets/${asset.id}`, 'DELETE', undefined, 409);
  const stable = durable!.slice(); failSave = true;
  await api(`/api/document-drafts/${draft.id}/publish`, 'POST', { expectedUpdatedAt: draft.updatedAt }, 507);
  assert.deepEqual(durable, stable); failSave = false;
  assert.equal((await api('/api/documents')).length, 0); assert.equal((await api('/api/document-drafts')).length, 1);
  const document = await api(`/api/document-drafts/${draft.id}/publish`, 'POST', { expectedUpdatedAt: draft.updatedAt });
  assert.equal(document.bodyMarkdown, complete.bodyMarkdown); assert.equal((await api('/api/document-drafts')).length, 0);
  await api(`/api/document-drafts/${draft.id}`, 'PUT', { expectedUpdatedAt: draft.updatedAt, state: complete }, 404);
  const editState = { ...complete, title: '草稿版本', bodyMarkdown: '草稿独立于已保存正文' };
  let editing = await api('/api/document-drafts', 'POST', { documentId: document.id, baseDocumentUpdatedAt: document.updatedAt, state: editState }, 201);
  const changed = await api(`/api/documents/${document.id}`, 'PUT', { ...document, bodyMarkdown: '另一个页面已保存的新正文' });
  await api(`/api/document-drafts/${editing.id}/publish`, 'POST', { expectedUpdatedAt: editing.updatedAt }, 409);
  assert.equal((await api(`/api/documents/${document.id}`)).bodyMarkdown, changed.bodyMarkdown);
  const copied = await api(`/api/document-drafts/${editing.id}/publish`, 'POST', { expectedUpdatedAt: editing.updatedAt, asNew: true });
  assert.notEqual(copied.id, document.id); assert.equal(copied.bodyMarkdown, editState.bodyMarkdown);
  editing = await api('/api/document-drafts', 'POST', { documentId: null, baseDocumentUpdatedAt: null, state: complete }, 201);
  const backup = await api('/api/export'); assert.equal(backup.documentDrafts.length, 1);
  await runtime.close(); runtime = await createLocalRuntime(sql, seed, storage, { dailyPushScheduler: false });
  assert.equal((await api('/api/document-drafts'))[0].id, editing.id); assert.equal((await api('/api/documents')).length, 2);
  const preview = await runtime.previewRestore(durable!.slice(), 'drafts.sqlite');
  assert.equal(preview.counts.document_drafts, 1);
  // An installed database with no new table must save its schema upgrade even
  // when the user never opens the draft editor and daily pushing stays off.
  await runtime.close(); const legacyPath = resolve(folder, 'legacy.sqlite'); await writeFile(legacyPath, durable!);
  const legacy = new DatabaseSync(legacyPath); legacy.exec('DROP TABLE document_drafts'); legacy.close();
  durable = new Uint8Array(await readFile(legacyPath)); const beforeUpgrade = saves;
  runtime = await createLocalRuntime(sql, seed, storage, { dailyPushScheduler: false }); assert.ok(saves > beforeUpgrade);
  assert.deepEqual(await api('/api/document-drafts'), []); assert.equal((await api('/api/documents')).length, 2);
});
